import uuid
from datetime import datetime

from sqlalchemy import BigInteger, CheckConstraint, ForeignKey, Index, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base
from app.db.types import UTCDateTime, str_enum, utcnow
from app.models.application import Application
from app.models.enums import DocumentCategory, DocumentStatus


class Document(Base):
    """Supporting PDF attached to an application. Physical files live under the private storage root."""

    __tablename__ = "documents"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    application_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("applications.id", ondelete="RESTRICT"), nullable=False
    )
    original_filename: Mapped[str] = mapped_column(String(255), nullable=False)
    # 32 lowercase hex chars, generated by the server; NULL only when intake failed before storage.
    storage_key: Mapped[str | None] = mapped_column(String(32), unique=True, nullable=True)
    category: Mapped[DocumentCategory] = mapped_column(str_enum(DocumentCategory, "document_category"), nullable=False)
    mime_type: Mapped[str] = mapped_column(String(100), nullable=False)
    size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)
    sha256: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    uploaded_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)
    status: Mapped[DocumentStatus] = mapped_column(str_enum(DocumentStatus, "document_status"), nullable=False)
    duplicate_of_id: Mapped[str | None] = mapped_column(
        String(36), ForeignKey("documents.id", ondelete="SET NULL"), nullable=True, index=True
    )
    description: Mapped[str | None] = mapped_column(String(500), nullable=True)
    # Set only for synthetic demo documents inserted by the seed; keeps reseeding idempotent.
    seed_key: Mapped[str | None] = mapped_column(String(50), nullable=True)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)

    application: Mapped[Application] = relationship()
    duplicate_of: Mapped["Document | None"] = relationship(remote_side=[id])

    __table_args__ = (
        Index("ix_documents_application_uploaded", "application_id", "uploaded_at"),
        Index("uq_documents_seed_key", "seed_key", unique=True),
        Index("ix_documents_application_sha256", "application_id", "sha256"),
        CheckConstraint("size_bytes >= 0", name="ck_documents_size_non_negative"),
        CheckConstraint("length(sha256) = 64", name="ck_documents_sha256_length"),
        CheckConstraint("duplicate_of_id IS NULL OR duplicate_of_id <> id", name="ck_documents_not_self_duplicate"),
    )
