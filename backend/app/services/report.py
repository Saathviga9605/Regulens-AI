"""Preliminary scrutiny report (PDF) generated server-side from persisted data only.

Uses PyMuPDF's HTML ``Story`` layout, which flows long content across pages. Every value that comes from user or
document input is HTML-escaped. No storage paths, tokens or other applications' data are included.
"""

import html
import io
import re
from datetime import datetime, timezone

import pymupdf
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import Application, Document, Finding, FindingReviewAction, ScrutinyRun
from app.models.enums import FindingKind
from app.services import audit, issuer_verification, processing as processing_service, review
from app.services.scrutiny import evaluation_rule

LABEL = "PRELIMINARY SCRUTINY — HUMAN REVIEW REQUIRED"
DISCLAIMER = (
    "This report is decision support generated by ReguLens AI from uploaded documents and configured rules. It is not "
    "an official AICTE decision, does not approve or reject the application, and is not an independent determination "
    "of any document's authenticity or of misconduct. Findings and anomaly indicators require human review. Expectation "
    "rules marked demo-only have not been verified against official sources. Issuer checks are simulated against "
    "synthetic records and were not verified with any issuing authority."
)
CSS = """
* { font-family: sans-serif; }
body { font-size: 9pt; color: #1e293b; }
h1 { font-size: 16pt; margin: 0; }
h2 { font-size: 12pt; margin-top: 12pt; border-bottom: 1px solid #94a3b8; }
h3 { font-size: 10pt; margin: 6pt 0 2pt 0; }
.label { background-color: #fde68a; color: #78350f; font-weight: bold; padding: 3pt; font-size: 11pt; }
.demo { color: #991b1b; font-weight: bold; }
.small { font-size: 8pt; color: #475569; }
.quote { font-family: monospace; font-size: 8pt; background-color: #f1f5f9; padding: 2pt; }
table { border-collapse: collapse; width: 100%; }
td, th { border: 1px solid #cbd5e1; padding: 2pt; font-size: 8pt; text-align: left; vertical-align: top; }
th { background-color: #e2e8f0; }
"""

_SEV = {"high": 0, "medium": 1, "low": 2, "info": 3}


def e(value) -> str:
    return html.escape("" if value is None else str(value))


def safe_filename(application_code: str, run_number: int) -> str:
    code = re.sub(r"[^A-Za-z0-9-]", "_", application_code)
    return f"ReguLens-preliminary-scrutiny-{code}-run{run_number}.pdf"


def _findings_html(findings: list[Finding], snapshot: list[dict], history: dict) -> str:
    if not findings:
        return "<p>No findings in this run (every enabled rule passed or was not applicable).</p>"
    out = []
    for f in findings:
        rule = evaluation_rule(snapshot, f.rule_id)
        origin = (f"Rule {e(f.rule_id)} v{e(f.rule_version)}" + (" — <span class='demo'>DEMO-ONLY RULE</span>"
                  if rule and rule.get("is_demo_only") else "")) if f.rule_id else f"Indicator: {e(f.detector)}"
        parts = [f"<h3>[{e(f.severity.value.upper())} · {e(f.outcome.value)}] {e(f.title)}</h3>",
                 f"<p class='small'>{origin} · human review: <b>{e(f.review_status.value.replace('_', ' '))}</b></p>",
                 f"<p>{e(f.explanation)}</p>"]
        if f.uncertainty:
            parts.append(f"<p><i>Uncertainty:</i> {e(f.uncertainty)}</p>")
        if f.missing_evidence:
            parts.append(f"<p><i>Missing evidence:</i> {e(f.missing_evidence)}</p>")
        citation = rule.get("citation") if rule else None
        if citation:
            page = citation.get("pdf_page_number")
            printed = citation.get("printed_page_label")
            location = f"PDF page {e(page)}" if page is not None else "PDF page unavailable"
            if printed:
                location += f" (printed page {e(printed)})"
            parts.append(
                f"<p class='small'>APH citation: {e(citation.get('clause_reference'))} · {location}</p>"
                f"<div class='quote'>{e(citation.get('quote'))}</div>"
            )
        for ev in f.evidence[:8]:
            where = e(ev.get("document_filename")) + (f", page {e(ev['page_number'])}" if ev.get("page_number") else "")
            quote = f"<div class='quote'>{e(ev['quote'])}</div>" if ev.get("quote") else ""
            parts.append(f"<p class='small'>Evidence: {where}</p>{quote}")
        for action in history.get(f.id, []):
            parts.append(f"<p class='small'>Reviewer action: {e(action.action_type.value)} by {e(action.actor_username)} "
                         f"({e(action.created_at.strftime('%Y-%m-%d %H:%M UTC'))}) → {e(action.new_status.value)}"
                         + (f": {e(action.note)}" if action.note else "") + "</p>")
        out.append("".join(parts))
    return "".join(out)


def build_report(session: Session, application: Application, run: ScrutinyRun) -> bytes:
    inst = application.institution
    findings = session.execute(select(Finding).where(Finding.run_id == run.id)).scalars().all()
    findings = sorted(findings, key=lambda f: (f.kind != FindingKind.RULE_FINDING, _SEV[f.severity.value], f.finding_key))
    history: dict[str, list] = {}
    for action in session.execute(select(FindingReviewAction).where(
            FindingReviewAction.finding_id.in_([f.id for f in findings])).order_by(FindingReviewAction.created_at)).scalars():
        history.setdefault(action.finding_id, []).append(action)
    docs = session.execute(select(Document).where(Document.application_id == application.id)
                           .order_by(Document.uploaded_at)).scalars().all()
    attempts = issuer_verification.latest_attempts(session, application.id)
    requests = review.list_requests(session, application)
    summary = run.summary or {}
    outcomes = summary.get("evaluation_outcomes", {})
    severities = summary.get("finding_severities", {})
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    demo = application.seed_key is not None or "(Synthetic)" in (inst.trust_name or "")

    doc_rows = []
    for d in docs:
        proc = processing_service.get_processing(session, d.id)
        doc_rows.append(f"<tr><td>{e(d.original_filename)}</td><td>{e(d.category.value)}</td><td>{e(d.status.value)}</td>"
                        f"<td>{e(proc.status.value if proc else 'not processed')}</td>"
                        f"<td>{e(proc.failure_reason if proc and proc.failure_reason else '')}</td></tr>")
    att_rows = [f"<tr><td>{e(a.document_filename)}</td><td>{e(a.outcome.value)}</td><td>{e(a.explanation)}</td></tr>"
                for a in attempts.values()]
    req_rows = [f"<tr><td>{e(r.requested_evidence)}</td><td>{e(r.status.value)}</td><td>{e(r.due_date or '—')}</td>"
                f"<td>{e(r.created_by)}</td><td>{e(', '.join(link.document_filename for link in r.documents) or '—')}</td></tr>"
                for r in requests]
    inconclusive = [f for f in findings if f.outcome.value == "inconclusive" and f.kind == FindingKind.RULE_FINDING]
    profile = next((item for item in run.rule_snapshot if item.get("ruleset_profile")), None)
    profile_id = profile.get("ruleset_profile", "production") if profile else "production"
    profile_version = profile.get("ruleset_version", "database") if profile else "database"
    demo_notice = profile.get("demo_notice") if profile else None

    body = f"""
<h1>ReguLens AI — Preliminary scrutiny report</h1>
<p class='label'>{LABEL}</p>
{"<p class='demo'>FICTIONAL DEMONSTRATION DATA — not a real institution or application.</p>" if demo else ""}
{"<p class='demo'>" + e(demo_notice) + " · this profile does not represent formal rule approval.</p>" if demo_notice else ""}
<p class='small'>Generated {e(generated)} · scrutiny run #{e(run.run_number)} ({e(run.id)}) · status {e(run.status.value)} ·
scrutiny reference date {e(run.scrutiny_date or 'unavailable')} (source: {e(run.scrutiny_date_source)}) ·
ruleset profile {e(profile_id)} v{e(profile_version)} · rule-set version {e(run.rule_set_version)}</p>
<h2>Application</h2>
<table><tr><th>Application</th><td>{e(application.application_code)} — {e(application.application_type.value)},
academic year {e(application.academic_year)}, internal status {e(application.status.value)}</td></tr>
<tr><th>Institution</th><td>{e(inst.name)} ({e(inst.institution_code)}), {e(inst.district)}, {e(inst.state)}</td></tr>
<tr><th>Trust / sponsoring body</th><td>{e(inst.trust_name)}</td></tr></table>
<h2>Summary</h2>
<p>Rule evaluations — pass: {e(outcomes.get('pass', 0))}, issue: {e(outcomes.get('issue', 0))},
inconclusive: {e(outcomes.get('inconclusive', 0))}, not applicable: {e(outcomes.get('not_applicable', 0))}.<br/>
Findings by severity — high: {e(severities.get('high', 0))}, medium: {e(severities.get('medium', 0))},
low: {e(severities.get('low', 0))}, info: {e(severities.get('info', 0))}
({e(summary.get('rule_findings', 0))} rule findings, {e(summary.get('anomaly_indicators', 0))} anomaly indicators).</p>
<h2>Documents and processing</h2>
<table><tr><th>File</th><th>Category</th><th>Intake</th><th>Processing</th><th>Notes</th></tr>{''.join(doc_rows) or '<tr><td colspan="5">No documents.</td></tr>'}</table>
<h2>Findings and anomaly indicators</h2>
{_findings_html(findings, run.rule_snapshot, history)}
<h2>Simulated issuer verification</h2>
<p class='demo'>{e(issuer_verification.SIMULATION_LABEL)}</p>
<table><tr><th>Document</th><th>Simulated outcome</th><th>Explanation</th></tr>{''.join(att_rows) or '<tr><td colspan="3">No simulated checks were run.</td></tr>'}</table>
<h2>Additional evidence requests</h2>
<table><tr><th>Requested evidence</th><th>Status</th><th>Due</th><th>Requested by</th><th>Linked documents</th></tr>{''.join(req_rows) or '<tr><td colspan="5">None.</td></tr>'}</table>
<h2>Limitations and inconclusive results</h2>
<p>{e(len(inconclusive))} rule result(s) were inconclusive (unreadable, ambiguous or missing evidence) and need manual
review. {" ".join(e(w) for w in run.warnings)} Extraction reads only explicitly labelled text; OCR depends on a local
Tesseract installation; classification confidence is a heuristic. Results on synthetic data say nothing about
real-world accuracy.</p>
<h2>Disclaimer</h2>
<p>{e(DISCLAIMER)}</p>
"""
    story = pymupdf.Story(html=body, user_css=CSS)
    buffer = io.BytesIO()
    writer = pymupdf.DocumentWriter(buffer)
    page_rect = pymupdf.paper_rect("a4")
    content = page_rect + (40, 50, -40, -50)
    more = True
    while more:
        device = writer.begin_page(page_rect)
        more, _ = story.place(content)
        story.draw(device)
        writer.end_page()
    writer.close()

    doc = pymupdf.open(stream=buffer.getvalue(), filetype="pdf")
    for number, page in enumerate(doc, start=1):
        page.insert_text((40, 30), "ReguLens AI - PRELIMINARY SCRUTINY - HUMAN REVIEW REQUIRED", fontsize=7, color=(0.47, 0.21, 0.06))
        page.insert_text((40, page.rect.height - 25), f"{application.application_code} - run #{run.run_number} - "
                         f"page {number} of {doc.page_count} - decision support only", fontsize=7, color=(0.3, 0.3, 0.3))
    doc.set_metadata({"title": f"Preliminary scrutiny report {application.application_code} run {run.run_number}",
                      "producer": "ReguLens AI", "creator": "ReguLens AI"})
    data = doc.tobytes(deflate=True)
    audit.record(session, "report.generated", "scrutiny_run", run.id, application_id=application.id,
                 details={"run_number": run.run_number, "findings": len(findings), "bytes": len(data)})
    session.commit()
    return data
